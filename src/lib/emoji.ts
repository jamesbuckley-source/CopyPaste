/** Everything in one list, used for search and favourites lookup. */
export const ALL_EMOJI: EmojiEntry[] = EMOJI_GROUPS.flatMap((group) => group.entries);

const BY_CHAR = new Map(ALL_EMOJI.map((entry) => [entry.char, entry]));

export function emojiByChar(char: string): EmojiEntry | undefined {
  return BY_CHAR.get(char);
}

/** Case-insensitive match on the name and the keywords. */
export function searchEmoji(query: string): EmojiEntry[] {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (terms.length === 0) return ALL_EMOJI;
  return ALL_EMOJI.filter((entry) => {
    const haystack = `${entry.name} ${entry.keywords}`.toLowerCase();
    return terms.every((term) => haystack.includes(term));
  });
}
