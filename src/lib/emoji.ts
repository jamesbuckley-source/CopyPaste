/**
 * A searchable slice of the Unicode emoji set.
 *
 * Deliberately curated rather than exhaustive: a few hundred entries covering the
 * ones people actually paste, each with the words someone would search for. The
 * full set is ~3,600 code points and would cost more bundle than it returns.
 *
 * Regional-indicator flags are left out on purpose: Windows has no flag glyphs and
 * renders them as the bare letter pairs ("GB"), which looks broken rather than
 * decorative.
 */

export interface EmojiEntry {
  char: string;
  name: string;
  keywords: string;
}

export interface EmojiGroup {
  title: string;
  entries: EmojiEntry[];
}

const group = (title: string, rows: [string, string, string][]): EmojiGroup => ({
  title,
  entries: rows.map(([char, name, keywords]) => ({ char, name, keywords })),
});

